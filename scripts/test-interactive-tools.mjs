import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import ts from 'typescript'
import React from 'react'
import { renderToStaticMarkup } from 'react-dom/server'

const root = path.resolve(import.meta.dirname, '..')
const temporary = fs.mkdtempSync(path.join(root, '.tool-tests-'))
function compile(file, name, replacements = []) {
  let source = fs.readFileSync(path.join(root, file), 'utf8')
  for (const [from, to] of replacements) source = source.replace(from, to)
  fs.writeFileSync(path.join(temporary, name), ts.transpileModule(source, {
    compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022, jsx: ts.JsxEmit.ReactJSX },
  }).outputText)
}
try {
  compile('lib/interactive-tools.ts', 'models.mjs')
  compile('lib/mohr-circle.ts', 'mohr-model.mjs')
  compile('components/mohr-plot.tsx', 'mohr-plot.mjs', [["'@/lib/mohr-circle'", "'./mohr-model.mjs'"]])
  compile('components/mohr-circle.tsx', 'mohr.mjs', [["'@/lib/mohr-circle'", "'./mohr-model.mjs'"], ["'@/components/mohr-plot'", "'./mohr-plot.mjs'"]])
  compile('components/interactive-tools.tsx', 'tools.mjs', [["'@/lib/interactive-tools'", "'./models.mjs'"], ["'@/lib/mohr-circle'", "'./mohr-model.mjs'"], ["'@/components/mohr-circle'", "'./mohr.mjs'"]])
  compile('lib/remark-number-headings.ts', 'headings.mjs')
  compile('lib/course-markdown.ts', 'markdown.mjs')
  compile('components/content-renderer.tsx', 'renderer.mjs', [
    ["'@/lib/remark-number-headings'", "'./headings.mjs'"], ["'@/lib/course-markdown'", "'./markdown.mjs'"], ["'@/components/interactive-tools'", "'./tools.mjs'"],
    [/import \{ Image,.*from '@\/components\/mdx-components'/, 'const Table = ({children}) => <div>{children}</div>; const Image = Table, ImageGrid = Table, Definition = Table, Formula = Table, Example = Table, Problem = Table, Solution = Table, Summary = Table;'],
  ])
  const { getInteractiveTool, evaluateTool } = await import(pathToFileURL(path.join(temporary, 'models.mjs')).href)
  const { transformMohr, parseMohrValues, expandMohrRange, elementArrows } = await import(pathToFileURL(path.join(temporary, 'mohr-model.mjs')).href)
  assert.equal(expandMohrRange(100, 50), 100)
  assert(expandMohrRange(100, 500) > 500)
  assert(expandMohrRange(200, -1200) > 1200)
  const tension = transformMohr({ x: 50, y: 0, shear: 0, theta: 0 }, 'stress')
  const compression = transformMohr({ x: -50, y: 0, shear: 0, theta: 0 }, 'stress')
  const stronger = transformMohr({ x: 80, y: 0, shear: 0, theta: 0 }, 'stress')
  const arrow = state => elementArrows(state, 100).find(item => item.key === 'x-1')
  assert(arrow(tension).to[0] > arrow(tension).from[0], 'Tension arrows must point away from the face')
  assert(arrow(compression).to[0] < arrow(compression).from[0], 'Compression arrows must point toward the face')
  assert(arrow(stronger).to[0] - arrow(stronger).from[0] > arrow(tension).to[0] - arrow(tension).from[0], 'Arrow length must grow with component magnitude at the same scale')
  assert.equal(elementArrows(transformMohr({ x: 0, y: 0, shear: 0, theta: 0 }, 'stress'), 100).length, 0)
  const shearArrows = elementArrows(transformMohr({ x: 0, y: 0, shear: 50, theta: 0 }, 'stress'), 100)
  assert.equal(shearArrows.filter(item => item.kind === 'shear').length, 4)
  assert(shearArrows.find(item => item.key === 'shear-x-1').to[1] < shearArrows.find(item => item.key === 'shear-x-1').from[1])
  const custom = parseMohrValues({ x: '350,5', y: '-125.75', shear: '2.5e2', theta: '-22.5' }, 'stress')
  assert.deepEqual(custom.input, { x: 350.5, y: -125.75, shear: 250, theta: -22.5 })
  assert.equal(parseMohrValues({ x: '', y: '0', shear: '0', theta: '0' }, 'stress').input, undefined)
  assert.equal(parseMohrValues({ x: 'Infinity', y: '0', shear: '0', theta: '0' }, 'stress').input, undefined)
  assert.equal(parseMohrValues({ x: '1e308', y: '-1e308', shear: '1e308', theta: '0' }, 'stress').input, undefined)
  const near = (actual, expected) => assert(Math.abs(actual - expected) < 1e-8, `${actual} != ${expected}`)
  const base = { x: 50, y: -10, shear: 20, theta: 0 }
  let mohr = transformMohr(base, 'stress')
  near(mohr.rotatedX, 50); near(mohr.rotatedY, -10); near(mohr.rotatedShear, 20)
  near(mohr.principal1, 20 + Math.sqrt(1300))
  near(mohr.principal2, 20 - Math.sqrt(1300))
  mohr = transformMohr({ ...base, theta: 90 }, 'stress')
  near(mohr.rotatedX, -10); near(mohr.rotatedY, 50); near(mohr.rotatedShear, -20)
  assert.equal(transformMohr({ ...base, theta: 45 }, 'stress').rotatedY, 0)
  assert.equal(transformMohr({ x: 1e-20, y: 0, shear: 0, theta: 0 }, 'stress').rotatedX, 1e-20)
  assert.equal(transformMohr({ x: 1e-20, y: 0, shear: 0, theta: 0 }, 'stress').principalAngle, 0)
  mohr = transformMohr({ ...base, theta: 180 }, 'stress')
  near(mohr.rotatedX, 50); near(mohr.rotatedShear, 20)
  const principal = transformMohr(base, 'stress')
  mohr = transformMohr({ ...base, theta: principal.principalAngle }, 'stress')
  near(mohr.rotatedShear, 0); near(mohr.rotatedX, principal.principal1)
  const sample = transformMohr({ x: 100, y: 150, shear: 100, theta: 0 }, 'stress')
  near(sample.radius, Math.sqrt(10625))
  near(sample.average, 125)
  near(sample.principal1, 228.07764064044153)
  near(sample.principalAngle, 52.01812173396324)
  near(sample.principalAngle2, -37.98187826603676)
  near(transformMohr({ x: 100, y: 150, shear: 100, theta: sample.principalAngle2 }, 'stress').rotatedX, sample.principal2)
  // Compare against independent tensor rotation; strain uses half the engineering shear.
  for (const mode of ['stress', 'strain']) for (const theta of [0, 15, 30, 45, 89, 90, 135, 180]) {
    const input = { x: 400, y: -200, shear: 300, theta }
    const state = transformMohr(input, mode)
    const shear = input.shear / (mode === 'strain' ? 2 : 1)
    const a = theta * Math.PI / 180, c = Math.cos(a), s = Math.sin(a)
    near(state.rotatedX, input.x * c * c + input.y * s * s + 2 * shear * s * c)
    near(state.rotatedY + state.rotatedX, input.x + input.y)
    near((state.rotatedX - state.average) ** 2 + state.rotatedTensorShear ** 2, state.radius ** 2)
    near(state.rotatedX * state.rotatedY - state.rotatedTensorShear ** 2, input.x * input.y - shear ** 2)
  }
  mohr = transformMohr({ x: 0, y: 0, shear: 300, theta: 45 }, 'strain')
  near(mohr.radius, 150); near(mohr.principal1, 150); near(mohr.rotatedX, 150); near(mohr.maxShear, 300)
  assert.equal(transformMohr({ x: 0, y: 0, shear: 0, theta: 180 }, 'stress').principalAngle, null)
  assert.equal(transformMohr({ x: -50, y: -50, shear: 0, theta: 45 }, 'stress').radius, 0)
  assert.throws(() => transformMohr({ ...base, x: NaN }, 'stress'))
  const stress = getInteractiveTool('esfuerzo-normal')
  const axial = getInteractiveTool('deformacion-axial')
  assert.equal(evaluateTool(stress, { force: '20', area: '100' }).results[0].value, 200)
  assert.equal(evaluateTool(stress, { force: '-20', area: '100' }).results[0].value, -200)
  assert.equal(evaluateTool(stress, { force: '0', area: '100' }).results[0].value, 0)
  assert.equal(evaluateTool(stress, { force: '1,5', area: '10' }).results[0].value, 150)
  const result = evaluateTool(axial, { force: '20', area: '100', length: '1000', modulus: '200' })
  assert.deepEqual(result.results.map(item => item.value), [1, 0.001, 200])
  for (const area of ['0', '-1', '', ' ', 'Infinity', '0x10', 'abc']) assert.equal(evaluateTool(stress, { force: '20', area }).results.length, 0)
  assert.equal(evaluateTool(axial, { force: '20', area: '100', length: '1000', modulus: '0' }).results.length, 0)
  assert.equal(evaluateTool(stress, { force: '1e308', area: '1e-300' }).results.length, 0)
  assert.equal(getInteractiveTool('unknown'), undefined)
  const { ContentRenderer } = await import(pathToFileURL(path.join(temporary, 'renderer.mjs')).href)
  const render = contentMarkdown => renderToStaticMarkup(React.createElement(ContentRenderer, { document: { contentMarkdown } }))
  const html = render('<Tool id="esfuerzo-normal" />\n\n<Tool id="deformacion-axial" title="Explora una barra" />')
  assert(html.includes('200'))
  assert(html.includes('Explora una barra'))
  assert.equal((html.match(/class="course-tool /g) || []).length, 2)
  const ids = [...html.matchAll(/<input id="([^"]+)"/g)].map(match => match[1])
  assert.equal(ids.length, 6)
  assert.equal(new Set(ids).size, 6, 'Inputs in repeated tool instances must have distinct labels')
  assert(render('::tool{id="esfuerzo-normal"}').includes('Esfuerzo normal'))
  assert(render('<Tool id="unknown" />').includes('Herramienta no disponible'))
  assert(!render('```mdx\n<Tool id="esfuerzo-normal" />\n```').includes('class="course-tool'))
  const circles = render('<Tool id="mohr-esfuerzos" />\n\n<Tool id="mohr-deformaciones" />')
  assert(circles.includes('Círculo de Mohr · Esfuerzos'))
  assert(circles.includes('Círculo de Mohr · Deformaciones'))
  assert(circles.includes('γ/2'))
  assert.equal((circles.match(/type="range"/g) || []).length, 8)
  assert.equal((circles.match(/type="text"/g) || []).length, 8, 'Both circles must accept directly typed numeric values')
  assert(circles.includes('Ajustar σx con deslizador'))
  assert(!circles.includes('Ajuste con deslizadores'))
  assert(circles.includes('θp₂'))
  assert(circles.includes('A′'))
  assert(circles.includes('viewBox="0 0 510 380"'), 'The compact plot must remain readable beside the element')
  assert(circles.includes('τmáx = R'))
  assert(circles.includes('Escala visual'))
  assert(circles.includes('Ampliar rango de los deslizadores'))
  assert(circles.includes('data-component="x-1"'))
  assert(!circles.includes('min-w-[420px]'), 'The graph must fit narrow containers without horizontal scrolling')
  const svgIds = [...circles.matchAll(/ id="([^"]+)"/g)].map(match => match[1])
  assert.equal(new Set(svgIds).size, svgIds.length, 'SVG markers and slider IDs must be unique across multiple tools')
  assert(!circles.includes('<iframe'))
  assert(!circles.includes('NaN'))
  console.log('PASS: Mohr tensor invariants, principal angles, engineering shear factor, zero-radius states, calculators and Markdown integration.')
} finally {
  if (!temporary.startsWith(path.join(root, '.tool-tests-'))) throw new Error('Unexpected test directory')
  fs.rmSync(temporary, { recursive: true, force: true })
}
